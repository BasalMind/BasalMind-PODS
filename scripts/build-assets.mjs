// Generates src/panel_assets.generated.js from panel/*.js|css and the schema
// bundle, so the Worker serves the panel and setup pages from its own release
// bytes (no Durable Object wake, no external URL). Each asset carries its
// sha256 so the release manifest can pin it.
//   node scripts/build-assets.mjs           write
//   node scripts/build-assets.mjs --check   exit 1 when the file is stale
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PANEL_FACETS } from "../schema/dist/bundle.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "panel_assets.generated.js");
const SOURCES = ["panel.js", "panel.css", "setup.js", "labels.js", "did_genesis.js", "b64u.js"];

export function buildAssets() {
  const files = {};
  for (const name of SOURCES) files[`/assets/${name}`] = readFileSync(join(ROOT, "panel", name), "utf8");
  const meta = Object.fromEntries(Object.entries(PANEL_FACETS).map(([f, d]) => [f, { version: d.version, lists: d.lists }]));
  files["/assets/facets.js"] = "// Generated from schema/dist/bundle.js.\nexport const FACETS = " + JSON.stringify(meta, null, 2) + ";\n";
  const assets = {};
  for (const [path, body] of Object.entries(files)) {
    assets[path] = {
      type: path.endsWith(".css") ? "text/css; charset=utf-8" : "text/javascript; charset=utf-8",
      sha256: createHash("sha256").update(body).digest("hex"),
      body,
    };
  }
  return "// Generated by scripts/build-assets.mjs. Do not edit.\nexport const ASSETS = " + JSON.stringify(assets, null, 1) + ";\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = buildAssets();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
      console.error("src/panel_assets.generated.js is stale -- run npm run assets:build");
      process.exit(1);
    }
    console.log("panel assets are up to date");
  } else {
    writeFileSync(OUT, text);
    console.log("wrote src/panel_assets.generated.js");
  }
}
