// Generates schema/dist/ deterministically from the facet definitions:
//   <facet>.schema.json   JSON Schema (data document + op shape)
//   <facet>.sqlite.sql    SQLite migration: one table per list + <facet>_ops
//   manifest.json         spec_version, facets[], spec_cid, signature (null)
// `node schema/build.mjs --check` exits 1 when dist/ differs from a fresh build.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod/mini";
import { canonicalJson } from "./canonical.js";
import { itemSchema, opSchema, dataSchema } from "./lib.js";
import { facet as health } from "./facets/health.js";
import { facet as money } from "./facets/money.js";
import { facet as memoir } from "./facets/memoir.js";

export const SPEC_VERSION = 1;
export const FACETS = [health, money, memoir];
const HERE = dirname(fileURLToPath(import.meta.url));
const DIST = join(HERE, "dist");

const sha256 = (b) => createHash("sha256").update(b).digest();

// CIDv1, raw codec (0x55), sha2-256 multihash (0x12 0x20), base32 lower, 'b' prefix.
export function cidOf(bytes) {
  const raw = Buffer.concat([Buffer.from([0x01, 0x55, 0x12, 0x20]), sha256(bytes)]);
  const A = "abcdefghijklmnopqrstuvwxyz234567";
  let bits = 0, acc = 0, out = "";
  for (const b of raw) {
    acc = (acc << 8) | b; bits += 8;
    while (bits >= 5) { out += A[(acc >>> (bits - 5)) & 31]; bits -= 5; }
    acc &= (1 << bits) - 1;
  }
  if (bits > 0) out += A[(acc << (5 - bits)) & 31];
  return "b" + out;
}

const json = (v) => JSON.stringify(v, null, 2) + "\n";
const q = (s) => "'" + String(s).replaceAll("'", "''") + "'";
const SAFE = 9007199254740991;

function columnSql(rawName, prop, required) {
  const name = `"${rawName}"`; // quoted: some column names (when, ...) are SQL keywords
  let type = "TEXT";
  const checks = [];
  if (prop.type === "integer") type = "INTEGER";
  else if (prop.type === "boolean") { type = "INTEGER"; checks.push(`${name} IN (0, 1)`); }
  else if (prop.type === "array") checks.push(`json_valid(${name})`);
  if (prop.enum) checks.push(`${name} IN (${prop.enum.map((v) => (typeof v === "number" ? v : q(v))).join(", ")})`);
  if (prop.const !== undefined) checks.push(`${name} = ${typeof prop.const === "number" ? prop.const : q(prop.const)}`);
  if (prop.anyOf) { // z.union of number literals
    const vals = prop.anyOf.map((x) => x.const);
    if (vals.every((v) => v !== undefined)) checks.push(`${name} IN (${vals.map((v) => (typeof v === "number" ? v : q(v))).join(", ")})`);
    if (prop.anyOf.every((x) => typeof x.const === "number")) type = "INTEGER";
  }
  if (prop.type === "string") {
    if (prop.minLength !== undefined) checks.push(`length(${name}) >= ${prop.minLength}`);
    if (prop.maxLength !== undefined) checks.push(`length(${name}) <= ${prop.maxLength}`);
  }
  if (prop.type === "integer") {
    if (prop.minimum !== undefined && prop.minimum > -SAFE) checks.push(`${name} >= ${prop.minimum}`);
    if (prop.maximum !== undefined && prop.maximum < SAFE) checks.push(`${name} <= ${prop.maximum}`);
  }
  let def = "";
  if (prop.default !== undefined) {
    const d = prop.default;
    def = " DEFAULT " + (typeof d === "boolean" ? (d ? 1 : 0) : typeof d === "number" ? d : Array.isArray(d) ? q(JSON.stringify(d)) : q(d));
  }
  const nn = required ? " NOT NULL" : "";
  const chk = checks.length ? ` CHECK (${name} IS NULL OR (${checks.join(" AND ")}))` : "";
  return `  ${name} ${type}${nn}${def}${chk}`;
}

export function sqliteFor(facet) {
  const lines = [
    `-- Generated by schema/build.mjs from facet "${facet.name}" v${facet.version}. Do not edit.`,
    `-- One table per list (id TEXT PRIMARY KEY, columns, updated_at) plus an append-only`,
    `-- ${facet.name}_ops table: undo is a superseding op, nothing is rewritten in place.`,
    "",
  ];
  for (const [list, value] of Object.entries(facet.lists)) {
    const js = z.toJSONSchema(itemSchema(value), { io: "output", unrepresentable: "any" });
    const req = new Set(js.required ?? []);
    const cols = ["  id TEXT PRIMARY KEY"];
    for (const [name, prop] of Object.entries(js.properties)) {
      if (name === "id") continue;
      cols.push(columnSql(name, prop, req.has(name)));
    }
    lines.push(`CREATE TABLE IF NOT EXISTS ${facet.name}_${list} (`, cols.join(",\n"), ");", "");
  }
  lines.push(
    `CREATE TABLE IF NOT EXISTS ${facet.name}_ops (`,
    "  op_id TEXT PRIMARY KEY,",
    "  receipt_id TEXT NOT NULL,",
    "  op TEXT NOT NULL CHECK (op IN ('add', 'set', 'remove', 'undo')),",
    `  list TEXT CHECK (list IS NULL OR list IN (${Object.keys(facet.lists).map(q).join(", ")})),`,
    "  item_id TEXT,",
    "  value_json TEXT CHECK (value_json IS NULL OR json_valid(value_json)),",
    "  at TEXT NOT NULL,",
    `  supersedes TEXT REFERENCES ${facet.name}_ops (op_id)`,
    ");",
    `CREATE INDEX IF NOT EXISTS ${facet.name}_ops_receipt ON ${facet.name}_ops (receipt_id);`,
    "",
  );
  return lines.join("\n");
}

export function jsonSchemaFor(facet) {
  const opts = { io: "output", unrepresentable: "any" };
  return json({
    facet: facet.name,
    version: facet.version,
    status: facet.status,
    data: z.toJSONSchema(dataSchema(facet), opts),
    op: z.toJSONSchema(opSchema(facet), opts),
  });
}

export function buildAll() {
  const files = new Map();
  const entries = [];
  for (const f of FACETS) {
    const jsFile = `${f.name}.schema.json`;
    const sqlFile = `${f.name}.sqlite.sql`;
    const js = jsonSchemaFor(f);
    const sql = sqliteFor(f);
    files.set(jsFile, js);
    files.set(sqlFile, sql);
    // sha256 covers both generated files: sha256(schema bytes || 0x0a || sql bytes), hex.
    const digest = sha256(Buffer.concat([Buffer.from(js), Buffer.from("\n"), Buffer.from(sql)])).toString("hex");
    entries.push({ name: f.name, version: f.version, status: f.status, deployable: f.deployable, json_schema_file: jsFile, sqlite_file: sqlFile, sha256: digest });
  }
  const spec_cid = cidOf(Buffer.from(canonicalJson(entries)));
  files.set("manifest.json", json({ spec_version: SPEC_VERSION, facets: entries, spec_cid, signature: null }));
  files.set("tokens.json", readFileSync(join(HERE, "tokens.json"), "utf8"));
  return files;
}

function main() {
  const files = buildAll();
  if (process.argv.includes("--check")) {
    const bad = [];
    for (const [n, c] of files) {
      const p = join(DIST, n);
      if (!existsSync(p) || readFileSync(p, "utf8") !== c) bad.push(n);
    }
    if (existsSync(DIST)) for (const n of readdirSync(DIST)) if (!files.has(n)) bad.push(n + " (unexpected)");
    if (bad.length) { console.error("schema dist is out of date: " + bad.join(", ") + " -- run npm run schema:build"); process.exit(1); }
    console.log("schema dist is up to date (" + files.size + " files)");
    return;
  }
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(DIST, { recursive: true });
  for (const [n, c] of files) writeFileSync(join(DIST, n), c);
  console.log("wrote " + files.size + " files to schema/dist");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
